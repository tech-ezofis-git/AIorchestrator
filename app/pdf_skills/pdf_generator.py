class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas that adds running headers, footers, and dynamic page counts."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict[str, Any]] = []
        self.doc_title = "Document"
        self.theme_colors = resolve_theme(None)

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_decorations(self, page_count: int) -> None:
        self.saveState()
        w, h = self._pagesize
        left = 40.0
        right = w - 40.0

        primary_col = colors.HexColor(self.theme_colors.get("primary", "#1E40AF"))
        muted_col = colors.HexColor(self.theme_colors.get("text_muted", "#64748B"))
        border_col = colors.HexColor(self.theme_colors.get("border", "#E2E8F0"))

        # Header (pages > 1)
        if self._pageNumber > 1:
            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(primary_col)
            self.drawString(left, h - 28.0, "EZOFIS")

            self.setFont("Helvetica", 8)
            self.setFillColor(muted_col)
            short_title = self.doc_title[:45] + ("..." if len(self.doc_title) > 45 else "")
            self.drawString(left + 45.0, h - 28.0, f"|  {short_title}")

            self.setStrokeColor(border_col)
            self.setLineWidth(0.6)
            self.line(left, h - 34.0, right, h - 34.0)

        # Footer (all pages)
        self.setStrokeColor(border_col)
        self.setLineWidth(0.6)
        self.line(left, 36.0, right, 36.0)

        self.setFont("Helvetica", 8)
        self.setFillColor(muted_col)
        self.drawString(left, 24.0, "Generated by EZOFIS AI Orchestrator")

        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(right, 24.0, page_str)

        self.restoreState()


